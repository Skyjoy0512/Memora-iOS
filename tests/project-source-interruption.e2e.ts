import { randomUUID } from 'node:crypto';
import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { launchMemora, tapControl, tapTab } from './ui-helpers';
import { isolatedDatabase, sql } from './sqlite-fixture-helpers';

// Only the dedicated scenario's UI-created source is seeded as interrupted.
// Reopening must reconcile its status, never automatically fetch its URL.
test('interrupted source status recovers on launch without fetching content', { timeout: 180_000 }, async ({ app, device, screen }) => {
  await launchMemora(app, device, screen);
  const marker = 'source-interrupted-' + randomUUID();
  const project = 'Interrupted-' + randomUUID().slice(0, 8);
  const url = 'https://example.com/' + marker;
  await tapControl(screen.getByRole('button', { name: 'プロジェクト', exact: true }));
  await tapControl(screen.getByRole('button', { name: 'プロジェクトを作成', exact: true }).first());
  await screen.getByPlaceholder('例：新規アプリ').fill(project);
  await tapControl(screen.getByRole('button', { name: '作成', exact: true }));
  await tapControl(screen.getByRole('button', { name: '参考資料', exact: true }).last());
  await tapControl(screen.getByRole('button', { name: '参考資料を追加', exact: true }).first());
  const body = screen.getByRole('textbox', { name: 'ノート本文', exact: true });
  await tapControl(screen, body);
  await expect(body).toBeFocused();
  await body.pressSequentially(url);
  const closeKeyboard = screen.getByRole('button', { name: 'キーボードを閉じる', exact: true });
  if (await closeKeyboard.isVisible()) await tapControl(closeKeyboard);
  await expect(screen.getByRole('keyboard')).not.toBeVisible();
  await tapControl(screen.getByRole('button', { name: '保存', exact: true }));
  await expect(screen.getByRole('button', { name: /^example\.com/ }).first()).toBeVisible({ timeout: 60_000 });
  const identity = await device.foregroundApp();
  if (identity.bundleId !== 'app.bitrig.new.811eee03-bad9-4f5e-9d1d-d2820c1e93b4') throw new Error('Unexpected app');
  const database = isolatedDatabase(marker, identity.bundleId, 'memoraProjectSources.v2');
  const read = () => JSON.parse(sql(database, "SELECT CAST(data AS TEXT) FROM documents WHERE key='memoraProjectSources.v2';"));
  const sources = read();
  const matches = sources.filter((source: any) => source.originalURL === url);
  expect(matches).toHaveLength(1);
  const original = { ...matches[0] };
  expect(original.kind).toBe('web');
  matches[0].processingStatus = 'processing';
  const bytes = Buffer.from(JSON.stringify(sources), 'utf8').toString('hex');
  sql(database, `UPDATE documents SET data=X'${bytes}' WHERE key='memoraProjectSources.v2' AND instr(CAST(data AS TEXT), '${marker}')>0;`);
  expect(read().find((source: any) => source.id === original.id).processingStatus).toBe('processing');
  await app.restart();
  await tapTab(screen, 'ライブラリ');
  await tapControl(screen.getByRole('button', { name: 'プロジェクト', exact: true }));
  await tapControl(screen.getByText(project, { exact: true }).first());
  await tapControl(screen.getByRole('button', { name: '参考資料', exact: true }).last());
  await tapControl(screen.getByRole('button', { name: /^example\.com/ }).first());
  const notice = '処理は中断されました。ソースは保持しています。必要に応じて再試行してください。自動では再開しません。';
  await expect(screen.getByText(notice, { exact: true })).toBeVisible();
  await expect(screen.getByRole('button', { name: '再試行', exact: true })).toBeEnabled();
  const recovered = { ...read().find((source: any) => source.id === original.id) };
  expect(recovered.processingStatus).toBe('failed');
  expect(recovered.errorInformation).toBe(notice);
  delete recovered.errorInformation;
  delete recovered.processingStatus;
  const retained = { ...original };
  delete retained.errorInformation;
  delete retained.processingStatus;
  expect(recovered).toEqual(retained);
  expect(recovered.extractedTextReference).toBeUndefined();
  await app.screenshot('source-interruption-recovered-without-fetch');
  await app.restart();
  expect(read().find((source: any) => source.id === original.id)).toEqual({ ...retained, processingStatus: 'failed', errorInformation: notice });
});
