import { afterEach, test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { focusComposer, launchMemora, tapControl, tapTab } from './ui-helpers';

afterEach(async ({ device }) => { await device.setAppearance('light'); });

test('workflow polish: task planning, active filters and completion remain clear', { timeout: 180_000 }, async ({ app, device, screen }) => {
  await launchMemora(app, device, screen);
  await tapTab(screen, 'ジャーナル');
  await tapControl(screen, screen.getByLabel('すべてのタスクを見る'));
  await tapControl(screen, screen.getByRole('button', { name: 'タスクを追加', exact: true }).last());
  await screen.getByPlaceholder('すること').fill('Review proposal');
  await tapControl(screen, screen.getByRole('button', { name: '追加', exact: true }));
  const row = screen.getByRole('button', { name: /^Review proposal、/ });
  await tapControl(screen, row);
  await tapControl(screen, screen.getByLabel('進み具合'));
  await tapControl(screen, screen.getByRole('button', { name: '相手待ち', exact: true }));
  const planned = screen.getByRole('switch', { name: '取り組む日を設定', exact: true });
  await tapControl(screen, planned);
  await expect(planned).toBeChecked();
  await tapControl(screen, screen.getByRole('button', { name: '保存', exact: true }));
  await expect(screen.getByPlaceholder('タイトル')).not.toBeVisible();
  await expect(row).toBeVisible();
  await app.screenshot('tasks-planned-light');
  // SwiftUI exposes the combined row first, then its visible context text.
  await expect(screen.getByTestId(/^task.context\./).last()).toHaveText(/相手待ち · 取り組む日/);
  await tapControl(screen, screen.getByLabel('タスクを絞り込み'));
  await tapControl(screen, screen.getByRole('button', { name: '相手待ち', exact: true }));
  await expect(screen.getByTestId('tasks.activeFilters').first()).toBeVisible();
  await expect(row).toBeVisible();
  await tapControl(screen, screen.getByLabel('タスクを絞り込み'));
  await tapControl(screen, screen.getByRole('button', { name: '今日取り組む', exact: true }));
  await device.setAppearance('dark');
  await app.screenshot('tasks-active-filters-dark');
  await tapControl(screen, screen.getByLabel('絞り込みを解除'));
  await expect(screen.getByTestId('tasks.activeFilters').first()).not.toBeVisible();
  await tapControl(screen, screen.getByLabel('完了にする'));
  await tapControl(screen, screen.getByLabel('タスクを絞り込み'));
  await tapControl(screen, screen.getByRole('button', { name: '相手待ち', exact: true }));
  await expect(screen.getByText('条件に合うタスクはありません')).toBeVisible();
  await tapControl(screen, screen.getByLabel('絞り込みを解除'));
  await tapControl(screen, screen.getByRole('button', { name: '完了', exact: true }));
  await expect(row).toBeVisible();
  await expect(screen.getByTestId(/^task.context\./)).not.toBeVisible();
  await app.restart();
  await tapTab(screen, 'ジャーナル');
  await tapControl(screen, screen.getByLabel('すべてのタスクを見る'));
  await tapControl(screen, screen.getByRole('button', { name: '完了', exact: true }));
  await expect(row).toBeVisible();
});

test('workflow polish: project rename keeps edits until confirmed and saves from keyboard', { timeout: 180_000 }, async ({ app, device, screen }) => {
  await launchMemora(app, device, screen);
  await device.openLink('memora://projects');
  await tapControl(screen, screen.getByRole('button', { name: 'プロジェクトを作成', exact: true }).first());
  await screen.getByPlaceholder('例：新規アプリ').fill('Polish project');
  await tapControl(screen, screen.getByRole('button', { name: '作成', exact: true }));
  await device.openLink('memora://projects');
  await tapControl(screen, screen.getByLabel('Polish projectの操作'));
  await tapControl(screen, screen.getByRole('button', { name: '名前を変更', exact: true }));
  const name = screen.getByPlaceholder('プロジェクト名');
  await expect(name).toBeFocused();
  await expect(screen.getByRole('button', { name: '保存', exact: true })).toBeDisabled();
  await name.fill('Renamed project');
  await tapControl(screen, screen.getByRole('button', { name: 'キャンセル', exact: true }));
  await tapControl(screen, screen.getByRole('button', { name: '編集を続ける', exact: true }));
  await expect(name).toHaveValue('Renamed project');
  await tapControl(screen, screen.getByRole('button', { name: 'キャンセル', exact: true }));
  await tapControl(screen, screen.getByRole('button', { name: '変更を破棄', exact: true }));
  await expect(screen.getByLabel('Polish projectの操作')).toBeVisible();
  await tapControl(screen, screen.getByLabel('Polish projectの操作'));
  await tapControl(screen, screen.getByRole('button', { name: '名前を変更', exact: true }));
  await name.fill('   ');
  await expect(screen.getByRole('button', { name: '保存', exact: true })).toBeDisabled();
  await name.fill('Renamed project');
  await tapControl(screen, screen.getByRole('keyboard').getByTestId('Done'));
  await expect(screen.getByLabel('Renamed projectの操作')).toBeVisible();
  await app.screenshot('project-renamed-light');
  await app.restart();
  await device.openLink('memora://projects');
  await expect(screen.getByLabel('Renamed projectの操作')).toBeVisible();
  await device.setAppearance('dark');
  await app.screenshot('project-renamed-dark');
});

test('workflow polish: empty mail drafts return to Ask AI without clearing its draft', async ({ app, device, screen }) => {
  await launchMemora(app, device, screen);
  await tapTab(screen, 'Ask AI');
  const input = await focusComposer(screen);
  await input.fill('Keep this draft for later.');
  await screen.tapAt({ x: 220, y: 260 });
  await expect(screen.getByRole('keyboard')).not.toBeVisible();
  await tapTab(screen, 'ライブラリ');
  await tapControl(screen, screen.getByLabel('メニュー').first());
  await tapControl(screen, screen.getByRole('button', { name: '資料', exact: true }));
  await tapControl(screen, screen.getByLabel('資料の操作'));
  await tapControl(screen, screen.getByRole('button', { name: 'メール下書き', exact: true }));
  await expect(screen.getByText('下書きはありません', { exact: true })).toBeVisible();
  await app.screenshot('mail-drafts-empty-light');
  await device.setAppearance('dark');
  await app.screenshot('mail-drafts-empty-dark');
  await tapControl(screen, screen.getByRole('button', { name: 'Ask AIを開く', exact: true }));
  await expect(input).toHaveValue('Keep this draft for later.');
  await expect(screen.getByLabel('新しいチャット')).toBeVisible();
});
