import Foundation

/// How Memora's summaries write Japanese so they read easily: meaning kept, who
/// did what said plainly, one topic per paragraph, sentences a breath long,
/// nothing padded. Summaries only; Ask AI answers keep their own voice, because
/// these rules read oddly in a conversation. Current with yomiyasu v2.0.1
/// (github.com/nanaism/yomiyasu, MIT) and k16shikano's Japanese technical
/// writing guide (gist.github.com/k16shikano, Unlicense); see
/// docs/THIRD_PARTY.md.
enum ReadabilityGuide {
  /// For cloud models, which have room for the whole guide.
  static let rules = """
  # 読みやすい日本語で書く
  意味を変えないことを最優先にする。書き直す前の「主張」「何を重く扱うか」「言い切っているか推量か」「文の働き（事実・評価・依頼・予定・仮定・引用）」を、書き直した後も同じに保つ。
  - 主語・目的語・述語をそろえ、「誰が」「何を」したかを省かずに書く。「これ」「それ」ではなく、指す先が分かる具体的な名詞で書く。
  - 実施済みの変更・現在の動作・今後の予定を時制で書き分け、完了した変更を予定のように書かない。断定と推量、依頼と可能を混ぜない。
  - 原文にない主体・原因・条件・数値・感情・評価を足さない。ぼかした語を、勝手に狭い事実へ置き換えない。
  - 会議・資料・ツールなど人でないものを主語にして「〜が決めた」「〜が語る」のように擬人化しない。道具や仕組みの働きを客観的に述べる文はそのまま書く。
  - 比喩の動詞（壊れる・倒す・溶かす・効く・潰すなど）は、「うっかり」「ようやく」などの含みを残してふだんの言葉にする。「骨が折れる」など定着した慣用句は残す。「確実に」「必ず」など元にない強い語は足さない。
  - 前置き・まとめの決まり文句（「重要なのは〜」「結論から言うと」「いかがでしたでしょうか」）、二重否定、意味のない強調を書かない。評価を述べる文は、評価を述語に移して残す。
  - 否定対比（AではなくB）は、否定が意味や比重を担っているなら否定のまま残し、2文に分けない。
  - 漢語を助詞を落として詰めた句（「書類不備発見時は」）は、語を残して助詞と動詞を補ってほどく（「書類の不備を発見したときは」）。
  - 一つの段落には一つの話題だけを置き、段落の最初の文で何の話かが分かるようにする。改行は、話題や説明の段階が変わるところで意味のまとまりごとに入れる。
  - 本文で言い終えた内容を「まとめると」などで言い直すだけの文や段落は削る。次にすることや予定を述べる文は残す。
  - 一文はおよそ30〜45字、読点は0〜2個を目安にする。長い文は、目的・理由・順序のつながりを残せる範囲で分ける。主題・主語・目的語の直後で間を取るだけの読点（「〜は、」「〜には、」「〜を、」）は外し、条件・逆接や長い句を読み分ける読点は残す。
  - 「資料を、全員へ。」のようなコピー調や、「速い。軽い。安い。」のような評価語だけの短い文を並べない。主語・目的語から述語へ続けて読める文は一続きに書く。
  - ルールを「契約」、原文や比較の基準を「正本」のように、実際の役割より大げさな名詞を使わない。専門用語・識別子・数値・単位はそのまま保つ。
  - 絵文字、文末のコロン、ダッシュ記号（—、―、──）を書かない。「日時：10時」のようなラベルと値のコロンは残す。
  - 補助動詞と形式名詞はひらがなで書く（実行して下さい→してください、出来ます→できます、確認して頂く→確認していただく、試して見る→試してみる、する事→すること、する為→するために）。
  - 違うものを「同じ」とまとめず、似た語を言い換えて増やさない。同じものは同じ語で呼ぶ。読み手が一度に覚えておくことは一つずつ増やす。
  """

  /// For the on-device model, whose window is small: the rules that matter most.
  static let compactRules = """
  書き方: 意味を変えず、誰が何をしたかを具体的な名詞で書く。事実と予定・依頼と可能を混ぜず、実施済み・現在・予定を時制で書き分ける。原文にない情報や評価を足さず、断定を弱めたり強めたりしない。一文は30〜45字ほどで、読点は2個まで。前置きや決まり文句を書かない。補助動詞と「事」「為」はひらがなで書く。
  """
}
