/// How Memora's AI writes Japanese so it reads easily: who did what said
/// plainly, one topic per paragraph, sentences a breath long, nothing padded.
/// Drawn from yomiyasu (github.com/nanaism/yomiyasu, MIT) and k16shikano's
/// Japanese technical writing guide (gist.github.com/k16shikano, Unlicense);
/// see docs/THIRD_PARTY.md.
enum ReadabilityGuide {
  static let yomiyasuVersion = "2.4.0"
  static let yomiyasuRevision = "ae258d7a57b335673e30b88a018ae08d4f72c449"

  /// For cloud models, which have room for the whole guide.
  static let rules = """
  # 読みやすい日本語で書く
  - 意味の保持を最優先にする。主張・比重・言い切りの強さ・文の働き、条件・例外・否定・数量・単位・順序を変えない。自然に読める部分は残す。
  - 主語・目的語・述語と修飾先をそろえる。「誰が」「何を」したかは資料から確定できる範囲だけ補う。指示語の対象が不明なら推測で具体化しない。
  - 原文・提供資料・依頼のどこにもない人や部署、担当者・管理者などの役割を、動作の主語や通知先・依頼先として足さない。「担当者」を根拠なく特定の人や部署に狭めない。
  - 依頼（〜してください）と可能（〜できます）、事実と予定を混ぜない。実施済み・現在・予定は時制で書き分ける。
  - 道具や概念に意志・感情を持たせた表現は直す。システムの客観的な動作を述べる非生物主語や、定義済みの専門用語は残す。
  - 不自然な比喩は、元の含み・意味の広さ・主体・対象を保って平易に直す。文字どおりの動作は変えない。
  - 前置き・進行説明・定型の結び・否定対比は、削っても主張や比重が変わらない場合だけ省く。必要な評価・比較・反論・助言は残す。
  - 一つの段落には一つの話題だけを置き、段落の最初の文で何の話かが分かるようにする。改行は話題や説明の段階が変わる意味のまとまりで入れる。
  - 一文の平均30〜45字、読点0〜2個は目安であり、一文ずつ長さをそろえない。文字数のために意味や条件を省かず、目的・理由・対比のつながりが変わる分割はしない。
  - 推量・可能性・未定のことを断定に変えない。根拠のない注意書きや一般論を足さない。
  - 漢語を助詞抜きで詰めた句は、元の語を残して助詞と動詞を補う。主語・目的語と述語のつながりを分断する読点は外すが、条件や逆接を読み分ける読点は残す。
  - 補助動詞と形式名詞はひらがなで書く（してください、できます、いただく、試してみる、すること、するため）。専門用語・識別子・数量・単位はそのまま保つ。
  - 違うものを「同じ」とまとめず、似た語を言い換えて増やさない。同じものは同じ語で呼ぶ。
  - 読み手が一度に覚えておくことは一つずつ増やす。
  - 前後の文の対象・期間・比較項目の限定を、限定のない文へ勝手に持ち込まない。指示語・「同じ」・定義から同じ限定が掛かると確定できる場合だけ補う。
  - 「〜することができる」などの外枠は動詞へ戻す。ただし確認済みの結果・成立条件・義務・経験・可能・頻度・評価は保ち、「こと」の数を減らすことを目的にしない。
  - 議事録では出席者・発言者・作業の実行者・担当を引き受けた人を区別する。発言しただけで担当にせず、担当の記載がないだけで「担当未定」としない。報告・提案・賛否・合意の範囲・期限・経過を保つ。
  - 結論や重要な決定を先に書き、その後に根拠や詳細を置く。
  - 1段落は2〜3文を目安にし、話題が変わるところで空行を入れる。表示幅に合わせた手動改行は入れない。
  - 決定・変更点・期限など拾い読みしたい短い語句だけを **太字** にする。文全体や段落全体を太字にしない。
  - 箇条書きは1項目1論点。長い回答は短い見出しで分け、同じ内容を概要と本文で繰り返しすぎない。
  - 通常の見出しは短い項目名や動作にする。見出しから外した警告・条件・結論・範囲・順序・手段は本文に残す。見出しだけで警告を伝える指定がある場合は警告を残す。
  - 指定されたテンプレート・見出し・表・スキーマを優先し、キー・型・列名・必須性・null許容を変えない。指定された要約の範囲で情報を整理し、整形だけを理由に情報を省かない。決定・ToDoや担当は資料の根拠があるものだけ記載する。
  - 「結果の確かめ」「案の比べ」のような他動詞の連用形名詞は、「結果を確かめる」「結果の確認」など自然な形にする。「見直し」「組み合わせ」、定着した名称や引用はそのまま保つ。
  - 専門分野と意味が資料で確定するときだけ、不自然な直訳を定着した専門用語へ直す。画面の項目名・部品名・識別子を勝手に言い換えず、分野や仕様を推測しない。
  - 英語の短い術語を漢字1字に直訳した不自然な名詞は、文脈で意味が確定するときだけ定着した呼び名にする（ソフトウェアの版→バージョン、一覧の頭→先頭、lintの印→指摘）。出版物の版、目印、慣用句、引用、定義済みの名前は機械的に置換しない。何を指すか不明なら原文を保つ。
  - スライドの見出しと1行の箇条書きに限り、間を作るだけの読点を省く。逆接・条件・理由・目的・名詞の並び・短い時の句や、外すと係り受けが変わる読点、引用内の読点は残す。通常の文章にはこの省略を適用せず、指定のページ数・順序・項目順・スキーマを変えない。
  - 提出前に資料と照合し、数値・日付・固有名詞・担当・否定・確度・条件が変わっていないか確認する。資料にない保証や因果を足さず、検査したという宣言や内部の検討過程は本文に出さない。
  """

  /// For the on-device model, whose window is small: the rules that matter most.
  static let compactRules = """
