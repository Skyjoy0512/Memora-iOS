  """

  static let summaryRules = """
  議事録の品質:
  - 原文に明示された因果・理由・条件は、結論を親の箇条書き、理由や条件を2スペース字下げした子の箇条書きで示す。子には「理由：」「条件：」「影響：」など関係を明記し、単なる前後関係や推測を因果に変えない。無関係な項目は同列にする。指定された表や見出しは変更しない。
