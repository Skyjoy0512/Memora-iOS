import Foundation
import UIKit

/// Reads the general pasteboard only when the person explicitly asks to add
/// what they copied. Change counts are owned by the main actor so a copy that
/// was already attached is not added twice.
enum PasteboardIntake {
  /// The most text one copied note can add.
  static let maximumTextCharacters = 10_000
  /// The attachment name shown in the composer strip.
  static let maximumTitleCharacters = 40
  /// The same file bound used by attachment storage.
  static let maximumImageBytes = 50 * 1024 * 1024

  @MainActor private static var lastHandledChangeCount: Int?
  /// Pasteboard managers mark concealed content with these types. They are
  /// never normal text or image input, so they are refused before reading.
  private static let concealedTypes: Set<String> = [
    "org.nspasteboard.concealedtype",
    "org.nspasteboard.transienttype",
    "org.nspasteboard.autogeneratedtype"
  ]

  /// One usable copy. Exactly one of `url`, `text` or `imageData` is set.
  struct Reading: Equatable, Sendable {
    var changeCount: Int
    var title: String
    var url: URL?
    var text: String?
    var imageData: Data?
  }

  @MainActor
  static func read() -> Reading? {
    read(from: .general)
  }

  /// Reports whether the general pasteboard holds usable content that has not
  /// been attached yet, without claiming it. Peeking never records the change
  /// count, so the explicit attachment path can still read the same copy.
  @MainActor
  static func peek() -> Reading? {
    reading(from: .general, claiming: false)
  }

  @MainActor
  static func read(from pasteboard: UIPasteboard) -> Reading? {
    reading(from: pasteboard, claiming: true)
  }

  @MainActor
  private static func reading(from pasteboard: UIPasteboard,
                              claiming: Bool) -> Reading? {
    let changeCount = pasteboard.changeCount
    guard changeCount != lastHandledChangeCount else { return nil }
    guard !containsPrivateContent(pasteboard) else { return nil }

    let rawText = pasteboard.string
    let text = rawText?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    let reading: Reading?
    if !text.isEmpty {
      if isURLCandidate(text) {
        guard let url = httpURL(from: text) else { return nil }
        reading = Reading(changeCount: changeCount, title: title(for: url),
          url: url, text: nil, imageData: nil)
      } else {
        let bounded = String(text.prefix(maximumTextCharacters))
        reading = Reading(changeCount: changeCount,
          title: String(bounded.prefix(maximumTitleCharacters)),
          url: nil, text: bounded, imageData: nil)
      }
    } else if let image = pasteboard.image,
              let data = image.jpegData(compressionQuality: 0.8),
              data.count <= maximumImageBytes {
      reading = Reading(changeCount: changeCount, title: "コピーした画像",
        url: nil, text: nil, imageData: data)
    } else {
      reading = nil
    }

    // The pasteboard changed while its content was being read; the copy is no
    // longer the one that was checked.
    guard let reading, pasteboard.changeCount == changeCount else { return nil }
    if claiming {
      lastHandledChangeCount = changeCount
    }
    return reading
  }

  /// A failed attachment may be tried again while the same copy is still on the
  /// pasteboard. Successful handling keeps the count recorded.
  @MainActor
  static func release(_ reading: Reading) {
    if lastHandledChangeCount == reading.changeCount {
      lastHandledChangeCount = nil
    }
  }

  @MainActor
  private static func containsPrivateContent(_ pasteboard: UIPasteboard) -> Bool {
    pasteboard.types.contains { type in
      let lowercasedType = type.lowercased()
      return concealedTypes.contains(lowercasedType) ||
        lowercasedType.hasPrefix("com.apple.uikit.pboard.private")
    }
  }

  private static func isURLCandidate(_ text: String) -> Bool {
    let lowercased = text.lowercased()
    return (lowercased.hasPrefix("http://") || lowercased.hasPrefix("https://")) &&
      !text.contains(where: \.isWhitespace) &&
      !text.unicodeScalars.contains(where: { CharacterSet.controlCharacters.contains($0) })
  }

  private static func httpURL(from text: String) -> URL? {
    guard text.utf8.count <= 8_192,
          let components = URLComponents(string: text),
          let scheme = components.scheme?.lowercased(),
          scheme == "http" || scheme == "https",
          components.user == nil, components.password == nil,
          components.port == nil || components.port == (scheme == "https" ? 443 : 80),
          let host = components.host?.lowercased().trimmingCharacters(in: CharacterSet(charactersIn: ".")),
          ProjectSourceURL.isPublicHostname(host),
          let url = components.url else { return nil }
    return url
  }

  private static func title(for url: URL) -> String {
    let value = url.host ?? url.absoluteString
    return String(value.prefix(maximumTitleCharacters))
  }
}
